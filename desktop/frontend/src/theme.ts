export function chartPalette(mode: ThemeMode) {
  const p = palette[mode]
  return {
    up: p.up,
    down: p.down,
    accent: p.accent,
    purple: p.purple,
    amber: p.amber,
    cyan: p.cyan,
    grid: p.grid,
    axis: p.axis,
    text: p.text,
    textSub: p.textSub,
    tooltipBg: p.tooltipBg,
    tooltipBorder: p.tooltipBorder,
    tooltipText: p.tooltipText,
    card: p.card,
  }
}

